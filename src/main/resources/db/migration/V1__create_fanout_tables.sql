CREATE TABLE FANOUT_RULE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(200) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    SORT_ORDER NUMBER(10) NOT NULL,
    MATCH_TYPE VARCHAR2(30) NOT NULL,
    URL_PATTERN VARCHAR2(2000) NOT NULL,
    TIMEOUT_MS NUMBER(10) DEFAULT 60000 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_FANOUT_RULE_ENABLED CHECK (ENABLED IN (0, 1)),
    CONSTRAINT CHK_FANOUT_RULE_MATCH_TYPE CHECK (MATCH_TYPE IN ('REGEX', 'STARTS_WITH'))
);

CREATE TABLE TARGET_SERVER (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(200) NOT NULL,
    TARGET_URL VARCHAR2(2000) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_TARGET_SERVER_ENABLED CHECK (ENABLED IN (0, 1))
);

CREATE TABLE FANOUT_RULE_TARGET (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RULE_ID NUMBER NOT NULL,
    TARGET_SERVER_ID NUMBER NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    SORT_ORDER NUMBER(10) NOT NULL,
    CONSTRAINT FK_FANOUT_RULE_TARGET_RULE FOREIGN KEY (RULE_ID) REFERENCES FANOUT_RULE(ID) ON DELETE CASCADE,
    CONSTRAINT FK_FANOUT_RULE_TARGET_SERVER FOREIGN KEY (TARGET_SERVER_ID) REFERENCES TARGET_SERVER(ID) ON DELETE CASCADE,
    CONSTRAINT CHK_FANOUT_RULE_TARGET_ENABLED CHECK (ENABLED IN (0, 1)),
    CONSTRAINT UK_FANOUT_RULE_TARGET UNIQUE (RULE_ID, TARGET_SERVER_ID)
);

CREATE INDEX IDX_FANOUT_RULE_ENABLED_ORDER ON FANOUT_RULE(ENABLED, SORT_ORDER, ID);
CREATE INDEX IDX_TARGET_SERVER_ENABLED ON TARGET_SERVER(ENABLED, ID);
CREATE INDEX IDX_RULE_TARGET_RULE_ORDER ON FANOUT_RULE_TARGET(RULE_ID, ENABLED, SORT_ORDER, ID);
CREATE INDEX IDX_RULE_TARGET_SERVER ON FANOUT_RULE_TARGET(TARGET_SERVER_ID, ID);
